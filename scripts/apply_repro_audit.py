DIMS = ["code", "env", "model", "data", "params", "seed", "eval", "provenance"]


def dims_for(entry: dict) -> dict[str, tuple[str, str]]:
    out = dict(COMMON)
    for key in DIMS:
        if key in entry:
            out[key] = entry[key]
    return out


def render_repro(entry: dict, level: str) -> str:
    dims = dims_for(entry)
    lines = [
        "[repro]",
        f'level = "{level}"',
        f'assessed_at = "{ASSESSED_AT}"',
        'assessed_by = "hand-audit + primary-source-check"',
        f'evidence_ref = "{entry["source"]}"',
        'evidence = ""',
    ]
    if entry.get("note"):
        lines.append(f'note = "{entry["note"]}"')
    lines.append("")
    for dim in DIMS:
        state, gap = dims[dim]
        lines += [f"[repro.{dim}]", f'state = "{state}"', f'gap = "{gap}"', ""]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    root = repo_root()
    recipes = {r.id: r for r in load_recipes(root)}
    load_taxonomy(root)  # 仅用于确保 registry 可读
    unknown = set(AUDIT) - set(recipes)
    missing = set(recipes) - set(AUDIT)
    if unknown or missing:
        print(f"审计表与 recipe 不一致: 多 {sorted(unknown)} / 少 {sorted(missing)}", file=sys.stderr)
        return 1

    # 只取 MARKER 之前的「原文」部分；后续所有纠错都在内存里累积，
    # 这样 dry-run 与正式写入走完全相同的判定路径。
    texts = {
        rid: r.path.read_text(encoding="utf-8").split(MARKER)[0]
        for rid, r in recipes.items()
    }

    applied_fixes = 0
    for rid, old, new in FIELD_FIXES:
        if rid not in recipes:
            print(f"未知 recipe: {rid}", file=sys.stderr)
            return 1
        text = texts[rid]
        if new and new in text:
            continue
        count = text.count(old)
        if count != 1:
            print(f"纠错未唯一命中 ({count}): {rid} :: {old[:70]!r}", file=sys.stderr)
            return 1
        texts[rid] = text.replace(old, new, 1)
        applied_fixes += 1

    print(f"事实纠错：{applied_fixes} 处（共登记 {len(FIELD_FIXES)} 处）")

    levels: dict[str, str] = {}
    for rid, r in recipes.items():
        entry = AUDIT[rid]
        dims = {d: dims_for(entry)[d][0] for d in DIMS}
        level = compute_level(dims, state_rank)
        levels[rid] = level
        base = texts[rid].rstrip() + "\n"
        generated = APPEND_BLOCKS.get(rid, "") + render_repro(entry, level)
        if not args.dry_run:
            r.path.write_text(base + MARKER + generated, encoding="utf-8")
        print(f"  {level}  {rid}")

    from collections import Counter

    dist = dict(sorted(Counter(levels.values()).items()))
    print(f"\n等级分布: {dist}")
    print(f"达到 L2 及以上（可复现）: {sum(1 for v in levels.values() if v in ('L2', 'L3', 'L4'))}/{len(levels)}")
    if args.dry_run:
        print("(dry-run，未写入)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

def execution_fields(r) -> list[tuple[str, str]]:
    """[execution] 的字段用 upsert 写入，兼容 Wordle 篇已有的 HF Jobs 段。"""
    slug = r.id.replace("/", "__")
    return [
        ("command", _q(f"python3 runner/train.py --recipe {r.id} --full")),
        ("entrypoint", _q("../../../../runner/train.py")),
        ("lockfile", _q(f"../../../../runner/locks/{slug}.lock.toml")),
        ("eval_script", _q("../../../../runner/eval.py")),
        ("zero_shot_script", _q("../../../../runner/zero_shot.py")),
        ("evidence", _q("evidence/run.json")),
        ("adapter_status", _q(ADAPTER_STATUS.get(r.id, DEFAULT_ADAPTER))),
    ]


def lock_template(r) -> str:
    slug = r.id.replace("/", "__")
    deps = [f"{k} = {_q(str(v))}"
            for k, v in sorted((r.get("dependencies", {}) or {}).items())]
    if not deps:
        deps = ["# 上游未给出精确 pin；由实跑环境 pip freeze 固化"]
    lines = [
        f"# baseline 锁定模板 · {r.id}",
        "# 由 scripts/apply_baseline_contract.py 生成。",
        "# 这不是已冻结的环境：在有网/有 GPU 环境跑 `runner/lock.py --apply` 固化。",
        "# 未解析到的字段保留 (未锁定)，不得手填猜测值。",
        "",
        f"recipe_id = {_q(r.id)}",
        f"experiment_id = {_q(r.id.replace('/', '-') + '-v1')}",
        f"model_id = {_q(str(r.get('model.base', '')))}",
        'model_revision = "(未锁定)"',
        f"dataset_id = {_q(str(r.get('dataset.name', '')))}",
        'dataset_revision = "(未锁定)"',
        'source_sha = "(未锁定)"',
        "",
        "[dependencies]",
        *deps,
        "",
        f"python_cuda = {_q(PYTHON_CUDA)}",
        f"determinism = {_q(DETERMINISM)}",
        "",
        "# 实际运行时执行：pip freeze > runner/locks/" + slug + ".freeze.txt",
        "",
    ]
    return "\n".join(lines)


def build_block(r) -> str:
    rid = r.id
    tier = "business" if rid in BUSINESS else "research"
    exp = rid.replace("/", "-") + "-v1"
    note = (
        "seed 为本仓库定义 baseline 时声明，上游训练 config 无 seed"
        if rid not in SEEDS else "seed 来自上游原文，保留原值"
    )
    lines = [
        "", MARKER,
        "[baseline_contract]",
        'state = "B0"',
        f"target_tier = {_q(tier)}",
        f"experiment_id = {_q(exp)}",
        f"revision_policy = {_q(REVISION_POLICY)}",
        f"determinism = {_q(DETERMINISM)}",
        f"python_cuda = {_q(PYTHON_CUDA)}",
        f"single_variable = {_q(SINGLE_VARIABLE)}",
        f"seed_origin = {_q(note)}",
        "",
        "[resources]",
        f"gpu = {_q(RESOURCES.get(rid, '待实跑确认（按模型规模与 batch 估）'))}",
        'note = "B3 业务档需要实测卡时与显存；此处为预估值，不作为验收依据"',
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    from recipe_lab.baseline import audit_one, load_contract

    root = repo_root(ROOT)
    LOCK_DIR.mkdir(parents=True, exist_ok=True)
    recipes = sorted(load_recipes(root), key=lambda x: x.id)

    # --- pass 1: 字段与模板 ---
    for r in recipes:
        text = r.path.read_text(encoding="utf-8")
        # 已迁移的配置由维护者维护；不能重置seed/split/task路由或覆盖真实环境锁。
        if MARKER in text:
            continue
        rid = r.id
        seed = SEEDS.get(rid, 42)
        text = upsert_scalar(text, "train", "seed", str(seed))
        text = upsert_scalar(text, "train", "data_seed", str(seed))
        text = upsert_scalar(text, "evaluation", "split", _q(SPLITS[rid]))
        text = upsert_scalar(text, "evaluation", "multi_run", "true")
        text = upsert_scalar(text, "evaluation", "held_out", "true")
        text = upsert_scalar(text, "evaluation", "seed", str(seed))
        if rid in METRICS:
            arr = "[" + ", ".join(_q(m) for m in METRICS[rid]) + "]"
            text = upsert_scalar(text, "evaluation", "metrics", arr)
        if not r.get("budget"):
            text = upsert_scalar(text, "budget", "smoke_steps", "5")
            text = upsert_scalar(text, "budget", "full_steps", "150")
        # Wordle 篇已有 [execution]（HF Jobs + papermill），必须用 upsert
        # 往原段里加键；直接再写一个 [execution] 会产生重复表，TOML 直接报错。
        for key, literal in execution_fields(r):
            text = upsert_scalar(text, "execution", key, literal)
        if MARKER not in text:
            text = text.rstrip("\n") + "\n" + build_block(r)
        r.path.write_text(text, encoding="utf-8")

        # 修正 [repro] 里因新增 runner 而过时的 gap 文案（状态不变）
        text = r.path.read_text(encoding="utf-8")
        text = text.replace(
            "无执行入口脚本；14 篇上游均为 .ipynb，本仓库未提供 runner / train.py",
            "上游 14 篇均为 .ipynb；本仓库已提供统一 runner，但那是我们自建的执行层，"
            "不等于能重放上游 notebook",
        )
        r.path.write_text(text, encoding="utf-8")

        lockfile = LOCK_DIR / (rid.replace("/", "__") + ".lock.toml")
        if not lockfile.exists():
            lockfile.write_text(lock_template(r), encoding="utf-8")

    # --- pass 2: 按 checks 重算 state，防止虚报 ---
    contract = load_contract(root)
    count = {}
    for r in sorted(load_recipes(root), key=lambda x: x.id):
        a = audit_one(r, contract)
        text = r.path.read_text(encoding="utf-8")
        # 只改 [baseline_contract] 内的 state；[repro.*] 里也有 state 键，
        # 全局 re.sub 会误伤，所以走按段定位的 upsert。
        text = upsert_scalar(text, "baseline_contract", "state", _q(a.computed))
        r.path.write_text(text, encoding="utf-8")
        count[a.computed] = count.get(a.computed, 0) + 1

    print(f"已处理 {len(recipes)} 篇 · lock 模板 {len(recipes)} 份")
    print("状态分布：", count)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
